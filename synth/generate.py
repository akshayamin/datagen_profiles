"""Materialise a derived config: generated tables with the source's exact DDL, small lookups copied unchanged."""

from __future__ import annotations

import time

import yaml
from dbldatagen.core import DataGenPlan, generate
from pyspark.sql import functions as F


def load_config(path: str) -> dict:
    with open(path) as fh:
        return yaml.safe_load(fh)


def save_config(cfg: dict, path: str) -> None:
    with open(path, "w") as fh:
        yaml.safe_dump(cfg, fh, sort_keys=False, width=140, allow_unicode=True)


def _q(text: str | None) -> str:
    return "'" + (text or "").replace("\\", "\\\\").replace("'", "\\'") + "'"


def _column_ddl(col: dict, force_not_null: bool) -> str:
    ddl = f"`{col['name']}` {col['type']}"
    if force_not_null or not col.get("nullable", True):
        ddl += " NOT NULL"
    if col.get("comment"):
        ddl += f" COMMENT {_q(col['comment'])}"
    return ddl


def _cast_type(type_text: str) -> str:
    # CHAR/VARCHAR exist only in table schemas; insert as string and let the table enforce the length
    t = type_text.lower()
    return "string" if t.startswith("char") or t.startswith("varchar") else type_text


def create_target(spark, pt: dict, table_format: str = "delta") -> None:
    """(Re)create the target table with the source DDL: types, NOT NULL, comments, partitioning, clustering."""
    pk = {c.lower() for c in pt["primary_key"]}
    cols = ",\n  ".join(_column_ddl(c, c["name"].lower() in pk) for c in pt["columns"])
    layout = ""
    if pt.get("partition_columns"):
        layout = "\nPARTITIONED BY (" + ", ".join(f"`{c}`" for c in pt["partition_columns"]) + ")"
    elif pt.get("clustering_columns") and table_format.lower() == "delta":
        layout = "\nCLUSTER BY (" + ", ".join(f"`{c}`" for c in pt["clustering_columns"]) + ")"
    comment = f"\nCOMMENT {_q(pt['comment'])}" if pt.get("comment") else ""
    if table_format.lower() == "delta":
        spark.sql(f"CREATE OR REPLACE TABLE {pt['target']} (\n  {cols}\n) USING DELTA{layout}{comment}")
    else:
        spark.sql(f"DROP TABLE IF EXISTS {pt['target']}")
        spark.sql(f"CREATE TABLE {pt['target']} (\n  {cols}\n) USING {table_format}{layout}{comment}")


def check_config(cfg: dict) -> list[str]:
    """Problems in a (possibly hand-edited) config, before anything is written. Empty means it is consistent."""
    problems = []
    try:
        plan = DataGenPlan.model_validate(cfg["plan"])
    except Exception as e:  # noqa: BLE001 - report pydantic's message as is
        return [f"plan: {e}"]
    planned = {t.name: {c.name.lower() for c in t.columns} for t in plan.tables}
    targets = {pt["target"] for pt in cfg["post"]["tables"]}
    for pt in cfg["post"]["tables"]:
        cols = {c["name"].lower() for c in pt["columns"]}
        for k in pt["primary_key"]:
            if k.lower() not in cols:
                problems.append(f"{pt['name']}: primary key column {k} is not a column")
        for fk in pt["foreign_keys"]:
            if fk["parent"] not in targets:
                problems.append(f"{pt['name']}.{fk['column']}: FK parent {fk['parent']} is not a target")
        if pt.get("copy"):
            bad = [i for i, r in enumerate(pt.get("copy_rows") or []) if len(r) != len(pt["columns"])]
            if bad:
                problems.append(f"{pt['name']}: copy_rows {bad[:5]} don't have {len(pt['columns'])} values")
            continue
        if pt["name"] not in planned:
            problems.append(f"{pt['name']}: no table of that name in plan")
            continue
        missing = sorted(cols - planned[pt["name"]])
        if missing:
            problems.append(f"{pt['name']}: columns not generated by the plan: {missing}")
        unknown = sorted({d.lower() for d in pt["drop"]} - planned[pt["name"]])
        if unknown:
            problems.append(f"{pt['name']}: helper columns to drop are not in the plan: {unknown}")
    return problems


def drop_foreign_keys(spark, cfg: dict, only: list[str] | None = None) -> None:
    """Existing FKs would block replacing a parent table, so remove them before (re)writing targets."""
    for pt in cfg["post"]["tables"]:
        if (not only or pt["name"] in only) and pt["foreign_keys"] and spark.catalog.tableExists(pt["target"]):
            for fk in pt["foreign_keys"]:
                spark.sql(f"ALTER TABLE {pt['target']} DROP FOREIGN KEY IF EXISTS (`{fk['column']}`)")


def write_table(spark, cfg: dict, name: str, table_format: str = "delta", dfs: dict | None = None, log=print) -> int:
    """Generate (or copy) one target and write it with the source DDL. Returns its row count.

    Tables don't depend on each other: linked keys come from shared value functions, not from reading the parent,
    so every target can be written at the same time.
    """
    pt = next(pt for pt in cfg["post"]["tables"] if pt["name"] == name)
    t0 = time.time()
    create_target(spark, pt, table_format)
    names = [c["name"] for c in pt["columns"]]
    if pt.get("copy") and "copy_rows" in pt:
        # rows embedded by 01 as text: the source isn't needed; the cast below restores the DDL types
        schema = ", ".join(f"`{n}` string" for n in names)
        df = spark.createDataFrame([tuple(r) for r in pt["copy_rows"]], schema)
    elif pt.get("copy"):
        df = spark.table(pt["source"]).select(*[F.col(f"`{n}`") for n in names])  # configs from before copy_rows
    else:
        dfs = dfs if dfs is not None else generate(spark, DataGenPlan.model_validate(cfg["plan"]))  # lazy frames
        df = dfs[pt["name"]].drop(*pt["drop"])
    types = {c["name"].lower(): _cast_type(c["type"]) for c in pt["columns"]}
    # insertInto is positional: follow the target's own column order (partition columns may move to the end)
    order = spark.table(pt["target"]).columns
    df = df.select(*[F.col(f"`{n}`").cast(types[n.lower()]).alias(n) for n in order])
    df.write.insertInto(pt["target"])
    count = spark.table(pt["target"]).count()
    log(f"{pt['target']}: {count:,} rows ({'copied' if pt.get('copy') else 'generated'}, "
        f"source {pt['source_rows']:,}) in {time.time() - t0:.0f}s")
    return count


def add_key_constraints(spark, cfg: dict, only: list[str] | None = None, log=print) -> None:
    """Informational Unity Catalog PKs, then FKs (each FK needs its parent's PK). Nothing checks the data."""
    tables = [pt for pt in cfg["post"]["tables"] if not only or pt["name"] in only]
    for pt in tables:
        if pt["primary_key"]:
            # CASCADE also clears FKs left from an earlier run
            spark.sql(f"ALTER TABLE {pt['target']} DROP PRIMARY KEY IF EXISTS CASCADE")
            keys = ", ".join(f"`{c}`" for c in pt["primary_key"])
            spark.sql(f"ALTER TABLE {pt['target']} ADD CONSTRAINT {pt['name']}_pk PRIMARY KEY ({keys})")
    col_type = {(pt["target"], c["name"].lower()): c["type"].lower() for pt in cfg["post"]["tables"]
                for c in pt["columns"]}
    for pt in tables:
        for fk in pt["foreign_keys"]:
            spark.sql(f"ALTER TABLE {pt['target']} DROP FOREIGN KEY IF EXISTS (`{fk['column']}`)")
            child = col_type.get((pt["target"], fk["column"].lower()))
            parent = col_type.get((fk["parent"], fk["parent_column"].lower()))
            if child != parent:
                # Unity Catalog needs identical types; the source DDL differs, so the key stays undeclared
                log(f"{pt['target']}.{fk['column']}: FK not declared ({child} vs parent {parent})")
                continue
            spark.sql(f"ALTER TABLE {pt['target']} ADD CONSTRAINT {pt['name']}_{fk['column']}_fk "
                      f"FOREIGN KEY (`{fk['column']}`) REFERENCES {fk['parent']} (`{fk['parent_column']}`)")


def generate_tables(spark, cfg: dict, table_format: str = "delta", add_constraints: bool = True,
                    log=print, only: list[str] | None = None) -> dict[str, int]:
    """Generate (or copy) every table in ``cfg`` and write it to its target. Returns target -> row count.

    Safe to re-run: Delta targets are replaced with CREATE OR REPLACE (history and grants kept) and every key constraint
    is dropped-if-exists before being added. ``only`` limits the run to some target names. Run one copy at a time.
    """
    constraints = add_constraints and table_format.lower() == "delta"
    if constraints:
        drop_foreign_keys(spark, cfg, only)
    dfs = generate(spark, DataGenPlan.model_validate(cfg["plan"]))
    counts = {pt["target"]: write_table(spark, cfg, pt["name"], table_format, dfs, log)
              for pt in cfg["post"]["tables"] if not only or pt["name"] in only}
    if constraints:
        add_key_constraints(spark, cfg, only, log)
    return counts
